import { useState } from "react";
import {
  Bar,
  BarChart,
  CartesianGrid,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from "recharts";

import { useGetCategoryPerformanceQuery } from "@/api/analyticsApi";

const currencyFormatter = new Intl.NumberFormat("en-BD", {
  style: "currency",
  currency: "BDT",
  maximumFractionDigits: 0,
});

const numberFormatter = new Intl.NumberFormat("en-BD");

export default function CategoryPerformanceChart() {
  const [limit, setLimit] = useState(5);

  const { data, isLoading, isError, refetch } = useGetCategoryPerformanceQuery({
    limit,
  });

  return (
    <section className="rounded-xl border border-slate-200 bg-white p-5 sm:p-6">
      <div className="mb-5 flex flex-col justify-between gap-3 sm:flex-row sm:items-center">
        <div>
          <h2 className="text-lg font-semibold text-slate-900">
            Category Performance
          </h2>
          <p className="mt-1 text-sm text-slate-500">
            Revenue generated by each category.
          </p>
        </div>

        <select
          value={limit}
          onChange={(event) => setLimit(Number(event.target.value))}
          aria-label="Number of categories"
          className="rounded-lg border border-slate-200 bg-white px-3 py-2 text-sm text-slate-700 outline-none focus:border-orange-500"
        >
          <option value={5}>Top 5</option>
          <option value={10}>Top 10</option>
          <option value={20}>Top 20</option>
        </select>
      </div>

      {isLoading ? (
        <div className="h-80 animate-pulse rounded-lg bg-slate-100" />
      ) : isError ? (
        <div className="flex h-80 flex-col items-center justify-center gap-3 text-center">
          <p className="text-sm text-red-600">
            Unable to load category performance.
          </p>
          <button
            type="button"
            onClick={() => refetch()}
            className="rounded-lg border border-slate-200 px-4 py-2 text-sm hover:bg-slate-50"
          >
            Retry
          </button>
        </div>
      ) : !data?.categories.length ? (
        <div className="flex h-80 items-center justify-center text-sm text-slate-500">
          No category sales data available.
        </div>
      ) : (
        <div className="h-80 w-full">
          <ResponsiveContainer width="100%" height="100%">
            <BarChart
              data={data.categories}
              margin={{ top: 10, right: 8, left: 8, bottom: 8 }}
            >
              <CartesianGrid
                strokeDasharray="3 3"
                vertical={false}
                stroke="#e2e8f0"
              />

              <XAxis
                dataKey="categoryName"
                tick={{ fontSize: 11, fill: "#64748b" }}
                axisLine={false}
                tickLine={false}
                interval={0}
                angle={-20}
                textAnchor="end"
                height={65}
              />

              <YAxis
                tickFormatter={(value: number) => numberFormatter.format(value)}
                tick={{ fontSize: 12, fill: "#64748b" }}
                axisLine={false}
                tickLine={false}
                width={55}
              />

              <Tooltip
                formatter={(value, name) => [
                  name === "Revenue"
                    ? currencyFormatter.format(Number(value))
                    : numberFormatter.format(Number(value)),
                  name,
                ]}
                contentStyle={{
                  borderRadius: 12,
                  border: "1px solid #e2e8f0",
                  fontSize: 12,
                }}
              />

              <Bar
                dataKey="totalRevenue"
                name="Revenue"
                fill="#ea580c"
                radius={[5, 5, 0, 0]}
                maxBarSize={48}
              />
            </BarChart>
          </ResponsiveContainer>
        </div>
      )}
    </section>
  );
}
